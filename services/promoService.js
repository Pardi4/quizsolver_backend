const BASE_PLN_PRICES = {
  starter: 4.99,
  popular: 14.99,
  pro: 39.00
};

const BASE_USD_PRICES = {
  starter: 1.99,
  popular: 4.99,
  pro: 14.99
};

function normalizePromoCode(rawCode) {
  if (!rawCode) return '';
  return String(rawCode).trim().toUpperCase().replace(/[^A-Z0-9_-]/g, '');
}

/**
 * Checks if user is eligible for first-purchase only discounts
 */
function isUserFirstPurchase(user) {
  if (!user) return true;
  if (user.hasPurchasedCredits) return false;
  if (user.stats && user.stats.totalCreditsPurchased > 0) return false;
  if (Array.isArray(user.appliedCreditPurchases) && user.appliedCreditPurchases.length > 0) return false;
  return true;
}

/**
 * Validates a promo code against MongoDB and built-in list
 */
async function validatePromoCode(rawCode, user = null, packId = null) {
  const code = normalizePromoCode(rawCode);
  if (!code) {
    return { valid: false, message: 'Wpisz kod rabatowy.' };
  }

  // 1. Check MongoDB PromoCode collection first (if DB is connected)
  if (mongoose.connection && mongoose.connection.readyState === 1) {
    try {
      const dbPromo = await PromoCode.findOne({ code });
      if (dbPromo) {
        if (!dbPromo.active) {
          return { valid: false, message: 'Ten kod rabatowy jest nieaktywny.' };
        }
        if (dbPromo.expiresAt && new Date(dbPromo.expiresAt) < new Date()) {
          return { valid: false, message: 'Ten kod rabatowy wygasł.' };
        }
        if (dbPromo.maxUses > 0 && dbPromo.usedCount >= dbPromo.maxUses) {
          return { valid: false, message: 'Limit użyć tego kodu rabatowego został wyczerpany.' };
        }
        if (dbPromo.firstPurchaseOnly && !isUserFirstPurchase(user)) {
          return { valid: false, message: 'Ten kod rabatowy jest przeznaczony wyłącznie na pierwsze doładowanie.' };
        }

        const percent = Math.min(Math.max(Number(dbPromo.discountPercent) || 10, 1), 50);
        return {
          valid: true,
          code: dbPromo.code,
          discountPercent: percent,
          description: dbPromo.description || `Rabat ${percent}%`,
          fromDb: true
        };
      }
    } catch (err) {
      console.warn('[PromoService] DB lookup error:', err.message);
    }
  }

  // 2. Check built-in codes
  if (BUILTIN_PROMO_CODES[code]) {
    const builtin = BUILTIN_PROMO_CODES[code];
    if (builtin.firstPurchaseOnly && !isUserFirstPurchase(user)) {
      return { valid: false, message: 'Kod WELCOME10 jest przeznaczony wyłącznie na pierwsze doładowanie.' };
    }
    return {
      valid: true,
      code,
      discountPercent: builtin.percent,
      description: builtin.description,
      fromDb: false
    };
  }

  // 3. Check pattern for SUPPORT codes (generated by admin support message)
  if (code.startsWith('SUPPORT-') && code.length >= 10) {
    return {
      valid: true,
      code,
      discountPercent: 10,
      description: 'Kod wsparcia QuizSolver (-10%)',
      fromDb: false
    };
  }

  return { valid: false, message: 'Nieprawidłowy lub wygasły kod rabatowy.' };
}

/**
 * Calculates discounted price for pack in PLN
 */
function calculatePlnPrice(packId, discountPercent = 0) {
  const base = BASE_PLN_PRICES[packId] || 14.99;
  const clampedPercent = Math.min(Math.max(Number(discountPercent) || 0, 0), 50);
  if (clampedPercent <= 0) return base;
  return Math.round(base * (1 - clampedPercent / 100) * 100) / 100;
}

/**
 * Calculates discounted price for pack in USD
 */
function calculateUsdPrice(packId, discountPercent = 0) {
  const base = BASE_USD_PRICES[packId] || 4.99;
  const clampedPercent = Math.min(Math.max(Number(discountPercent) || 0, 0), 50);
  if (clampedPercent <= 0) return base;
  return Math.round(base * (1 - clampedPercent / 100) * 100) / 100;
}

/**
 * Increments usage count for MongoDB promo codes
 */
async function markPromoUsed(rawCode) {
  const code = normalizePromoCode(rawCode);
  if (!code) return;
  if (mongoose.connection && mongoose.connection.readyState === 1) {
    try {
      await PromoCode.updateOne({ code }, { $inc: { usedCount: 1 } });
    } catch (err) {
      console.warn('[PromoService] markPromoUsed failed:', err.message);
    }
  }
}

